// what a look wearing that picture falls back to for a player without his imports. A surface tile of a body (a
// repeating patch, not a whole sphere) falls back to that body's twin. Keyed by `pictureKey` of the picture's file
// name, never the name itself: his imported names stay on his machine (design 2.10), and this file ships.
/** A short, stable key of an imported picture's file name (FNV-1a, 32 bits, as 8 hex digits). */
export function pictureKey(name) {
  let h = 0x811c9dc5;
  for (let i = 0; i < name.length; i++) { h ^= name.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}
