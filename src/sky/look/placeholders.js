/** Every placeholder look as makeLook takes it, made with generate.js's presetLook, presetDials and PRESETS. */
export function placeholderLooks({ presetLook, presetDials, PRESETS }) {
  const out = {};
  for (const [id, s] of Object.entries(PLACEHOLDER_SPECS)) if (PRESETS[s.base]) out[id] = makeGenerated(s.base, s, { presetLook, presetDials, PRESETS }, id);
  return out;
}

function makeGenerated(base, o, { presetLook, presetDials, PRESETS }, id = '') {
  const P = PRESETS[base];
  const L = presetLook(base);
  // (wave B) the grade re-tuned under its Scattered air over its own (airTuned.js)
  const g = { recipe: P.recipe, version: 2, preset: base, seed: o.seed, dials: { ...presetDials(base, 2), ...(o.dials || {}), ...(PLACEHOLDER_GRADE[id] || {}) }, size: o.size || 1024 };
  if (L.generated.mix && !o.noMix) g.mix = { ...L.generated.mix, ...(o.mix || {}), dials: { ...L.generated.mix.dials, ...(o.mix?.dials || {}) } };
  for (const part of ['shape', 'belt', 'rings', 'volume']) {
    const own = o[part];
    if (own) {
      const start = newPart(part, own.kind || own.style);
      g[part] = { ...start, dials: { ...start.dials, ...(own.dials || {}) } };
    } else if (L.generated[part] && !o.noParts) g[part] = L.generated[part];
  }
  const layers = JSON.parse(JSON.stringify(L.layers));
  for (const [slot, l] of Object.entries(o.layers || {})) layers[slot] = { ...(layers[slot] || {}), ...l };
  // (wave B) where the grade stood at its range's end: its surface layer's own brightness or colour strength
  if (PLACEHOLDER_SURFACE[id]) layers.surface = { ...(layers.surface || {}), ...PLACEHOLDER_SURFACE[id] };
  return {
    name: o.name, group: PLACEHOLDER_GROUP, kind: 'sphere', mesh: 'planet_01_mesh',
    note: `A placeholder from the lore: ${o.lore} Generated by our own code (recipe version 2): no picture.${o.matched ? ' ' + o.matched : ''}`,
    generated: g, layers, adjust: { ...L.adjust, ...(o.adjust || {}) },
    // (the atmosphere brief's wave A) a table default he has never saved: it takes the air as a new version of
    // itself, Scattered from its recipe's start (a shaped body's: none round it), its own `air` over that
    // (wave A's critic) and the air tuned for this body against what it was made to look like (airTuned.js)
    air: { ...airStartFor(P.recipe, g.dials, { shaped: !!g.shape }), ...(o.air || {}), ...(PLACEHOLDER_AIR[id] || {}) },
  };
}

