// read as untouched too, whether it is this table's look or one of an earlier table's (PAST_PRINTS).

/** A look as the file holds it (what the page's Save writes for each look). */
export function savedForm(l) {
  const out = { name: l.name, group: l.group, note: l.note, kind: l.kind, mesh: l.mesh, layers: l.layers, adjust: l.adjust };
  if (l.generated) out.generated = l.generated;
  // (wave A) its air, only when it has one: a look without it is written, and printed, exactly as before
  if (l.air) out.air = l.air;
  return out;
}
/** (wave A) A table look as it was before the air came: the same look without its `air` (its print is the old table's). */
export function withoutAir(l) {
  if (!l || !l.air) return l;
  const { air, ...rest } = l;
  return rest;
}
/**
 * (wave A) Whether `look` is the table's `tableLook` untouched: the same print, or (a copy his file holds from before
 * the air came, which has none) the same print as the table's look without its air. Such a copy is a default he never
 * saved as his own, so it takes the table's look, air and all.
 */
export function sameAsTable(look, tableLook) {
  if (!look || !tableLook) return false;
  const p = placeholderPrint(look);
  if (p === placeholderPrint(tableLook)) return true;
  return !look.air && !!tableLook.air && p === placeholderPrint(withoutAir(tableLook));
}
// the same value with its keys in a fixed order and the page's own working fields (an underscore's) left out
function canonical(v) {
  if (Array.isArray(v)) return '[' + v.map(canonical).join(',') + ']';
  if (v && typeof v === 'object') return '{' + Object.keys(v).filter((k) => !k.startsWith('_') && v[k] !== undefined).sort().map((k) => JSON.stringify(k) + ':' + canonical(v[k])).join(',') + '}';
  return JSON.stringify(v) ?? 'null';
}
/** A short print of a look as the file holds it (FNV-1a over its canonical text). */
export function placeholderPrint(look) {
  const s = canonical(savedForm(look));
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return (h >>> 0).toString(16).padStart(8, '0');
}
