/** (wave B) Whether `look` (made whole as the page makes looks) is the generated twin `id` as an earlier table had it. */
export function isPastTwin(id, look) {
  return !!look && (TWIN_PAST_PRINTS[id] || []).includes(placeholderPrint(look));
}
/** Whether `look` (made whole as the page makes looks) is the placeholder `id` untouched: the table's look `tableLook` or an earlier table's. */
export function isUntouchedPlaceholder(id, look, tableLook) {
  if (!look || !(id in PLACEHOLDER_SPECS)) return false;
  const p = placeholderPrint(look);
  if (tableLook && sameAsTable(look, tableLook)) return true;
  return (PAST_PRINTS[id] || []).includes(p);
}

